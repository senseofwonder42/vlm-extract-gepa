"""Document registry: one line per document file, keyed by its content hash.

`doc_id = sha256(file bytes)`, so the id survives renames and the synthetic
set can be regenerated byte-for-byte from its seed. Origin (`real` or
`synthetic`) comes from the sub-directory of `data/raw/`.
"""

import hashlib
import re
from datetime import UTC, datetime
from pathlib import Path
from typing import Literal

import pymupdf
from loguru import logger
from pydantic import BaseModel

Origin = Literal["real", "synthetic"]
DOCUMENT_SUFFIXES = (".pdf", ".png", ".jpg", ".jpeg")
# Synthetic files are named syn_<index>_<layout>.<ext> by the generator.
_SYNTHETIC_NAME = re.compile(r"^syn_\d+_(?P<layout>[a-z_]+)\.[a-z]+$")


class DocRecord(BaseModel):
    """One registered document.

    Attributes:
        doc_id: sha256 of the file bytes.
        origin: `real` or `synthetic`.
        path: File path, relative to the working directory.
        pages: Page count (1 for images).
        added_at: Registration time (UTC, ISO 8601).
        layout: Synthetic layout, read from the file name (`None` for real documents).
    """

    doc_id: str
    origin: Origin
    path: str
    pages: int
    added_at: str
    layout: str | None = None


def file_sha256(path: Path) -> str:
    """Return the sha256 hex digest of a file.

    Args:
        path: File to hash.
    """
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _page_count(path: Path) -> int:
    if path.suffix.lower() != ".pdf":
        return 1
    with pymupdf.open(path) as pdf:
        return pdf.page_count


def load_registry(path: Path) -> list[DocRecord]:
    """Load the registry (empty if the file does not exist).

    Args:
        path: `registry.jsonl`.
    """
    if not path.exists():
        return []
    lines = path.read_text(encoding="utf-8").splitlines()
    return [DocRecord.model_validate_json(line) for line in lines if line.strip()]


def register(raw_dir: Path, registry_path: Path) -> list[DocRecord]:
    """Scan `raw_dir/{real,synthetic}` and append new documents to the registry.

    Files whose content is already registered (same doc_id) are skipped, so a
    duplicate download under another name never becomes a second document.

    Args:
        raw_dir: `data/raw`.
        registry_path: `data/registry.jsonl`.

    Returns:
        The newly registered records.
    """
    known = {record.doc_id for record in load_registry(registry_path)}
    new: list[DocRecord] = []
    now = datetime.now(UTC).isoformat(timespec="seconds")
    for origin in ("real", "synthetic"):
        folder = raw_dir / origin
        files = sorted(p for p in folder.glob("*") if p.suffix.lower() in DOCUMENT_SUFFIXES) if folder.exists() else []
        for path in files:
            doc_id = file_sha256(path)
            if doc_id in known:
                continue
            known.add(doc_id)
            match = _SYNTHETIC_NAME.match(path.name) if origin == "synthetic" else None
            new.append(DocRecord(doc_id=doc_id, origin=origin, path=str(path), pages=_page_count(path), added_at=now,
                                 layout=match["layout"] if match else None))
    if new:
        registry_path.parent.mkdir(parents=True, exist_ok=True)
        with registry_path.open("a", encoding="utf-8") as handle:
            for record in new:
                handle.write(record.model_dump_json() + "\n")
    logger.info("Registered {} new document(s) ({} total)", len(new), len(known))
    return new
